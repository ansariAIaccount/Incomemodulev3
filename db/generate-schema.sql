-- ═══════════════════════════════════════════════════════════════════════
-- generate-schema.sql — emit a portable DDL script for the public schema
-- ═══════════════════════════════════════════════════════════════════════
--
-- WHY THIS EXISTS
--
-- The 112 migrations that built this database live only in the hosted
-- project's `supabase_migrations` table. Nothing is checked in. Lose access
-- to the Supabase project and there is no route to a schema at all.
--
-- `supabase db dump` remains the AUTHORITATIVE route and you should prefer it
-- when you have project credentials — it captures grants, sequence ownership,
-- publication membership and other things this script does not. This exists
-- for when you do not have them, and so that a schema can be regenerated and
-- diffed as it changes.
--
-- HOW TO RUN
--
--   psql "$DATABASE_URL" -At -f generate-schema.sql > schema.sql
--
-- `-At` matters: -A turns off column alignment padding, -t drops the header
-- and row count. Without them the output is a formatted table, not SQL.
--
-- WHAT IT EMITS, in dependency order
--   1. extensions          4. tables (columns + defaults + NOT NULL)
--   2. enum types          5. primary keys, uniques, checks
--   3. functions           6. foreign keys  7. indexes
--                          8. views  9. triggers  10. RLS + policies
--
-- WHAT IT DOES NOT EMIT — read this before trusting the output
--   * grants / role membership          * sequence ownership beyond serial
--   * comments on objects               * row data (see seed-reference.sql)
--   * anything outside schema `public`
--   * the `auth` schema this database depends on — see 00-auth-shim.sql
--
-- VERIFY BY RESTORING. A DDL script that has never been restored is a
-- hypothesis. The procedure is in README.md and takes about ten minutes.
-- ═══════════════════════════════════════════════════════════════════════

\set ON_ERROR_STOP on

select '-- Generated by generate-schema.sql on ' || now()::date
    || ' from ' || current_database()
    || E'\n-- Target: PostgreSQL 15+. Restore 00-auth-shim.sql FIRST.'
    || E'\n\nset check_function_bodies = off;\n';

-- ── 1 · Extensions ─────────────────────────────────────────────────────
select E'\n-- ═══ EXTENSIONS ═══\n';
select 'create extension if not exists ' || quote_ident(extname) || ';'
from pg_extension
where extname not in ('plpgsql')
order by extname;

-- ── 2 · Enum types ─────────────────────────────────────────────────────
select E'\n-- ═══ ENUM TYPES ═══\n';
select 'create type public.' || quote_ident(t.typname) || ' as enum ('
     || string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) || ');'
from pg_type t
join pg_enum e on e.enumtypid = t.oid
join pg_namespace n on n.oid = t.typnamespace and n.nspname = 'public'
group by t.typname
order by t.typname;

-- ── 3 · Functions ──────────────────────────────────────────────────────
-- Emitted before tables: RLS policies and column defaults reference them.
select E'\n-- ═══ FUNCTIONS ═══\n';
select pg_get_functiondef(p.oid) || ';'
from pg_proc p
join pg_namespace n on n.oid = p.pronamespace and n.nspname = 'public'
where p.prokind = 'f'
order by p.proname;

-- ── 4 · Tables ─────────────────────────────────────────────────────────
-- Columns, types, defaults and NOT NULL only. Constraints come later so the
-- tables can be created in any order without dependency failures.
select E'\n-- ═══ TABLES ═══\n';
select 'create table if not exists public.' || quote_ident(c.relname) || E' (\n'
     || string_agg(
          '  ' || quote_ident(a.attname) || ' '
               || format_type(a.atttypid, a.atttypmod)
               || coalesce(' default ' || pg_get_expr(ad.adbin, ad.adrelid), '')
               || case when a.attnotnull then ' not null' else '' end,
          E',\n' order by a.attnum)
     || E'\n);'
from pg_class c
join pg_namespace n on n.oid = c.relnamespace and n.nspname = 'public'
join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
left join pg_attrdef ad on ad.adrelid = c.oid and ad.adnum = a.attnum
where c.relkind = 'r'
group by c.relname
order by c.relname;

-- ── 5 · Primary keys, unique and check constraints ────────────────────
select E'\n-- ═══ CONSTRAINTS (pk / unique / check) ═══\n';
select 'alter table public.' || quote_ident(rel.relname)
     || ' add constraint ' || quote_ident(con.conname) || ' '
     || pg_get_constraintdef(con.oid) || ';'
from pg_constraint con
join pg_class rel on rel.oid = con.conrelid
join pg_namespace n on n.oid = con.connamespace and n.nspname = 'public'
where con.contype in ('p','u','c')
order by case con.contype when 'p' then 1 when 'u' then 2 else 3 end,
         rel.relname, con.conname;

-- ── 6 · Foreign keys ───────────────────────────────────────────────────
-- Last of the constraints so every referenced table already exists.
-- NOTE: 73 of these point at auth.users. 00-auth-shim.sql must have created
-- that table (or its replacement) before this section runs.
select E'\n-- ═══ FOREIGN KEYS ═══\n';
select 'alter table public.' || quote_ident(rel.relname)
     || ' add constraint ' || quote_ident(con.conname) || ' '
     || pg_get_constraintdef(con.oid) || ';'
from pg_constraint con
join pg_class rel on rel.oid = con.conrelid
join pg_namespace n on n.oid = con.connamespace and n.nspname = 'public'
where con.contype = 'f'
order by rel.relname, con.conname;

-- ── 7 · Indexes ────────────────────────────────────────────────────────
-- Excludes those backing a pk/unique constraint, which section 5 recreates.
select E'\n-- ═══ INDEXES ═══\n';
select pg_get_indexdef(i.indexrelid) || ';'
from pg_index i
join pg_class ic on ic.oid = i.indexrelid
join pg_class tc on tc.oid = i.indrelid
join pg_namespace n on n.oid = ic.relnamespace and n.nspname = 'public'
where not exists (
  select 1 from pg_constraint c
  where c.conindid = i.indexrelid and c.contype in ('p','u')
)
order by tc.relname, ic.relname;

-- ── 8 · Views ──────────────────────────────────────────────────────────
select E'\n-- ═══ VIEWS ═══\n';
select 'create or replace view public.' || quote_ident(c.relname)
     || E' as\n' || pg_get_viewdef(c.oid, true)
from pg_class c
join pg_namespace n on n.oid = c.relnamespace and n.nspname = 'public'
where c.relkind = 'v'
order by c.relname;

-- ── 9 · Triggers ───────────────────────────────────────────────────────
select E'\n-- ═══ TRIGGERS ═══\n';
select pg_get_triggerdef(t.oid) || ';'
from pg_trigger t
join pg_class c on c.oid = t.tgrelid
join pg_namespace n on n.oid = c.relnamespace and n.nspname = 'public'
where not t.tgisinternal
order by c.relname, t.tgname;

-- ── 10 · Row level security ────────────────────────────────────────────
-- RLS is the ONLY thing protecting this data when the publishable anon key
-- is in a browser. If you restore the schema without this section, every
-- deal is readable by anyone holding that key.
select E'\n-- ═══ ROW LEVEL SECURITY ═══\n';
select 'alter table public.' || quote_ident(tablename) || ' enable row level security;'
from pg_tables where schemaname = 'public' and rowsecurity
order by tablename;

select E'\n-- ─── policies ───\n';
select 'create policy ' || quote_ident(policyname)
     || ' on public.' || quote_ident(tablename)
     || ' as ' || case when permissive = 'PERMISSIVE' then 'permissive' else 'restrictive' end
     || ' for ' || lower(cmd)
     || ' to ' || array_to_string(roles, ', ')
     || coalesce(E'\n  using (' || qual || ')', '')
     || coalesce(E'\n  with check (' || with_check || ')', '')
     || ';'
from pg_policies
where schemaname = 'public'
order by tablename, policyname;

select E'\n-- ═══ END ═══';
